pub fn modifiers(meta: i32) -> i32 {
    i32::from(meta & 1 != 0)
        | i32::from(meta & 0x1000 != 0) * 2
        | i32::from(meta & 2 != 0) * 4
        | i32::from(meta & 0x10000 != 0) * 8
        | i32::from(meta & 0x100000 != 0) * 16
        | i32::from(meta & 0x200000 != 0) * 32
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn physical_iso_keys_and_modifier_sides_are_preserved() {
        assert_eq!(usage(86, 0), Some(100));
        assert_eq!(usage(21, 54), Some(28));
        assert_eq!(usage(44, 53), Some(29));
        assert_eq!(usage(100, 58), Some(230));
        assert_eq!(usage(0, 29), Some(4));
        assert_eq!(usage(0, 3), None);
        assert_eq!(modifiers(0x1001), 3);
    }
}
